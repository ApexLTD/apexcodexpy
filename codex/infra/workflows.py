from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import MutableMapping, MutableSequence
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from pathlib import Path

from codex.infra.program import Executable
from codex.infra.result import ProgramResult
from codex.infra.tools import Version
from codex.infra.yamler import Yamler


@dataclass(frozen=True, kw_only=True)
class YamlWorkflow(ABC):
    name: str
    path: Path

    @property
    @abstractmethod
    def standards(self) -> Yamler:
        pass

    def sync(self, target: Path) -> Executable:
        path = target / self.path
        path.parent.mkdir(parents=True, exist_ok=True)

        old = Yamler.read(path).as_mapping()
        new = self.standards.as_mapping()

        if old == new:
            return ProgramResult(name=self.name).success(
                message=f"{self.name} workflow is up to date.\n"
            )

        self.standards.comment(
            "Auto Generated",
            f"By: Apex Codex {Version()}",
            f"At: {self._utcnow()}",
            "Do not edit this file manually!\n\n",
        ).dump_to(path)

        return self.success()

    def _utcnow(self) -> str:
        return datetime.now(tz=UTC).replace(microsecond=0).isoformat(sep=" ")

    def success(self) -> ProgramResult:
        return ProgramResult(name=self.name).success(
            message=f"{self.name} workflow succeeded.\n"
        )


@dataclass(frozen=True, kw_only=True)
class DependabotWorkflow(YamlWorkflow):
    name: str = "Dependabot"
    path: Path = Path(".github") / "dependabot.yml"

    @property
    def standards(self) -> Yamler:
        return Yamler.parse(
            {
                "version": 2,
                "updates": [
                    self._pip_config().as_mapping(),
                    self._gh_actions_config().as_mapping(),
                ],
            }
        )

    @staticmethod
    def _pip_config() -> Yamler:
        return Yamler.parse(
            {
                "package-ecosystem": "pip",
                "directory": "/",
                "schedule": {
                    "interval": "weekly",
                    "day": "thursday",
                },
                "groups": {
                    "python": {
                        "patterns": ["*"],
                    }
                },
            }
        )

    @staticmethod
    def _gh_actions_config() -> Yamler:
        return Yamler.parse(
            {
                "package-ecosystem": "github-actions",
                "directory": "/",
                "schedule": {
                    "interval": "weekly",
                    "day": "thursday",
                },
                "groups": {
                    "gh-actions": {
                        "patterns": ["*"],
                    }
                },
            }
        )


