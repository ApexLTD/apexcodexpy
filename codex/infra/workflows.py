from __future__ import annotations

import io
from abc import ABC, abstractmethod
from collections.abc import Mapping
from dataclasses import dataclass, field
from datetime import UTC, datetime
from functools import cached_property
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from codex.infra.program import Executable
from codex.infra.result import ProgramResult
from codex.infra.tools import Version


@dataclass(frozen=True)
class Yamler:
    _yaml: YAML = field(init=False, default_factory=YAML)

    def __post_init__(self) -> None:
        self._yaml.indent(mapping=2, sequence=4, offset=2)

    def yamlify(self, data: Any, anchor: str = "") -> Any:
        stream = io.StringIO()
        self._yaml.dump(data, stream)
        stream.seek(0)
        yaml = self._yaml.load(stream)

        if anchor:
            yaml.yaml_set_anchor(anchor, always_dump=True)

        return yaml


@dataclass(frozen=True, kw_only=True)
class YamlWorkflow(ABC):
    name: str
    path: Path

    @property
    @abstractmethod
    def standards(self) -> Mapping[Any, Any]:
        pass

    def sync(self, target: Path) -> Executable:
        yaml = YAML()
        yaml.indent(mapping=2, sequence=4, offset=2)

        path = target / self.path
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as stream:
            stream.writelines(
                [
                    "# Auto Generated\n",
                    "# By: Apex Codex\n",
                    f"# At: {self._utcnow()}\n",
                    "# Do not edit this file manually!\n\n",
                ]
            )
            yaml.dump(self.standards, stream)

        return self.success()

    def _utcnow(self) -> str:
        return datetime.now(tz=UTC).replace(microsecond=0).isoformat(sep=" ")

    def success(self) -> ProgramResult:
        return ProgramResult(name=self.name).success(
            message=f"{self.name} workflow succeeded.\n"
        )


@dataclass(frozen=True, kw_only=True)
class CheckCodeWorkflow(YamlWorkflow):
    name: str = "CheckCode"
    path: Path = Path(".github") / "workflows" / "check_code.yml"

    python_version: float | int = 3.13
    checkout_version: str = "v6"
    setup_python_version: str = "v6"

    @property
    def standards(self) -> Mapping[str, Any]:
        return {
            "name": "Validate Python Code",
            "on": {"pull_request": {"branches": ["main"]}},
            "permissions": {"contents": "read"},
            "jobs": self._jobs(),
        }

    def _jobs(self) -> dict[str, Any]:
        jobs = {
            "lint": self._job(
                name="Lint Code",
                command="codex lint --ci",
            ),
            "test-unit": self._job(
                name="Run unit tests",
                command="codex test unit --ci",
            ),
        }

        if Version().is_installed("pytest-docker"):
            jobs["test-integration"] = self._job(
                name="Run integration tests",
                command="codex test integration --ci",
            )

        if Version().is_installed("behave"):
            jobs["test-behaviour"] = self._job(
                name="Run behaviour tests",
                command="codex test behaviour --ci",
            )

        return jobs

    def _job(self, name: str, command: str) -> Mapping[str, Any]:
        return {
            "runs-on": "ubuntu-latest",
            "steps": [
                self._checkout,
                self._setup,
                {"name": name, "run": command},
            ],
        }

    @cached_property
    def _checkout(self) -> Any:
        return Yamler().yamlify(
            data={"uses": f"actions/checkout@{self.checkout_version}"},
            anchor="checkout",
        )

    @cached_property
    def _setup(self) -> Any:
        return Yamler().yamlify(
            data={
                "name": "Set up Python",
                "uses": "actions/setup-python@v6",
                "with": {
                    "python-version": self.python_version,
                    "pip-install": f"apexcodexpy=={Version()}",
                },
            },
            anchor="setup-python",
        )


@dataclass(frozen=True, kw_only=True)
class DependabotWorkflow(YamlWorkflow):
    name: str = "Dependabot"
    path: Path = Path(".github") / "dependabot.yml"

    @property
    def standards(self) -> Mapping[str, Any]:
        return {
            "version": 2,
            "updates": [
                self._pip_config(),
                self._gh_actions_config(),
            ],
        }

    @staticmethod
    def _pip_config() -> dict[str, Any]:
        return {
            "package-ecosystem": "pip",
            "directory": "/",
            "schedule": {
                "interval": "weekly",
                "day": "thursday",
            },
            "groups": {
                "python": {
                    "patterns": ["*"],
                }
            },
        }

    @staticmethod
    def _gh_actions_config() -> dict[str, Any]:
        return {
            "package-ecosystem": "github-actions",
            "directory": "/",
            "schedule": {
                "interval": "weekly",
                "day": "thursday",
            },
            "groups": {
                "gh-actions": {
                    "patterns": ["*"],
                }
            },
        }
