@dataclass(frozen=True)
class Yamler:
    _yaml: YAML = field(init=False, default_factory=YAML)

    def __post_init__(self) -> None:
        self._yaml.indent(mapping=2, sequence=4, offset=2)

    def yamlify(self, data: Any, anchor: str = "") -> Any:
        stream = io.StringIO()
        self._yaml.dump(data, stream)
        stream.seek(0)
        yaml = self._yaml.load(stream)

        if anchor:
            yaml.yaml_set_anchor(anchor, always_dump=True)

        return yaml


@dataclass(frozen=True, kw_only=True)
class YamlWorkflow(ABC):
    name: str
    path: Path

    @property
    @abstractmethod
    def standards(self) -> Mapping[Any, Any]:
        pass

    def sync(self, target: Path) -> Executable:
        yaml = YAML()
        yaml.indent(mapping=2, sequence=4, offset=2)

        path = target / self.path
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as stream:
            stream.writelines(
                [
                    "# Auto Generated\n",
                    "# By: Apex Codex\n",
                    f"# At: {self._utcnow()}\n",
                    "# Do not edit this file manually!\n\n",
                ]
            )
            yaml.dump(self.standards, stream)

        return self.success()

    def _utcnow(self) -> str:
        return datetime.now(tz=UTC).replace(microsecond=0).isoformat(sep=" ")

    def success(self) -> ProgramResult:
        return ProgramResult(name=self.name).success(
            message=f"{self.name} workflow succeeded.\n"
        )


@dataclass(frozen=True)
class PythonSetupStep:
    version: str = "v6"
    python: float | int = 3.13

    def yamlify(self) -> Any:
        return self._yaml

    @cached_property
    def _yaml(self) -> Any:
        return Yamler().yamlify(
            data={
                "name": "Set up Python",
                "uses": f"actions/setup-python@{self.version}",
                "with": {
                    "python-version": self.python,
                    "pip-install": f"apexcodexpy=={Version()}",
                },
            },
            anchor="setup-python",
        )


@dataclass(frozen=True)
class CheckoutStep:
    version: str = "v7"

    def yamlify(self) -> Any:
        return self._yaml

    @cached_property
    def _yaml(self) -> Any:
        return Yamler().yamlify(
            data={"uses": f"actions/checkout@{self.version}"},
            anchor="checkout",
        )


@dataclass(frozen=True, kw_only=True)
class CheckCodeWorkflow(YamlWorkflow):
    name: str = "CheckCode"
    path: Path = Path(".github") / "workflows" / "check_code.yml"

    _setup: Any = field(init=False, default_factory=PythonSetupStep().yamlify)
    _checkout: Any = field(init=False, default_factory=CheckoutStep().yamlify)

    @property
    def standards(self) -> Mapping[str, Any]:
        return {
            "name": "Validate Python Code",
            "on": {"pull_request": {"branches": ["main"]}},
            "permissions": {"contents": "read"},
            "jobs": {job.name: job.yamlify() for job in self._jobs() if job.is_enabled},
        }

    def _jobs(self) -> Iterable[CiJob]:
        yield (
            CiJob(name="lint")
            .with_step(self._checkout)
            .with_step(self._setup)
            .with_step(
                {
                    "name": "Lint Code",
                    "run": "codex lint --ci",
                }
            )
        )

        yield (
            CiJob(name="test-unit")
            .with_step(self._checkout)
            .with_step(self._setup)
            .with_step(
                {
                    "name": "Run unit tests",
                    "run": "codex test unit --ci",
                }
            )
        )

        yield (
            CiJob(name="test-integration")
            .enabled(when=Version().is_installed("pytest-docker"))
            .with_step(self._checkout)
            .with_step(self._setup)
            .with_step(
                {
                    "name": "Run integration tests",
                    "run": "codex test integration --ci",
                }
            )
        )

        yield (
            CiJob(name="test-behaviour")
            .enabled(when=Version().is_installed("behave"))
            .with_step(self._checkout)
            .with_step(self._setup)
            .with_step(
                {
                    "name": "Run behaviour tests",
                    "run": "codex test behaviour --ci",
                }
            )
        )


@dataclass(frozen=True)
class CiJob:
    name: str

    is_enabled: bool = True
    platform: str = "ubuntu-latest"
    steps: MutableSequence[Any] = field(default_factory=list)

    def with_step(self, step: Any) -> CiJob:
        self.steps.append(step)

        return self

    def enabled(self, when: bool) -> CiJob:
        return replace(self, is_enabled=when)

    def yamlify(self) -> Any:
        return {
            "runs-on": self.platform,
            "steps": self.steps,
        }


class CiStep:
    pass


