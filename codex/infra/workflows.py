from __future__ import annotations

import io
from abc import ABC, abstractmethod
from collections.abc import Mapping, MutableMapping, MutableSequence
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from functools import cached_property
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from codex.infra.program import Executable
from codex.infra.result import ProgramResult
from codex.infra.tools import Version


@dataclass(frozen=True, kw_only=True)
class YamlWorkflow(ABC):
    name: str
    path: Path

    @property
    @abstractmethod
    def standards(self) -> Yamler:
        pass

    def sync(self, target: Path) -> Executable:
        path = target / self.path
        path.parent.mkdir(parents=True, exist_ok=True)

        old = dict(Yamler.read(path).yamlify())
        new = dict(self.standards.yamlify())

        if old == new:
            return ProgramResult(name=self.name).success(
                message=f"{self.name} workflow is up to date.\n"
            )

        self.standards.comment(
            "Auto Generated",
            f"By: Apex Codex {Version()}",
            f"At: {self._utcnow()}",
            "Do not edit this file manually!\n\n",
        ).dump_to(path)

        return self.success()

    def _utcnow(self) -> str:
        return datetime.now(tz=UTC).replace(microsecond=0).isoformat(sep=" ")

    def success(self) -> ProgramResult:
        return ProgramResult(name=self.name).success(
            message=f"{self.name} workflow succeeded.\n"
        )


@dataclass(frozen=True, kw_only=True)
class DependabotWorkflow(YamlWorkflow):
    name: str = "Dependabot"
    path: Path = Path(".github") / "dependabot.yml"

    @property
    def standards(self) -> Yamler:
        return Yamler.parse(
            {
                "version": 2,
                "updates": [
                    self._pip_config().yamlify(),
                    self._gh_actions_config().yamlify(),
                ],
            }
        )

    @staticmethod
    def _pip_config() -> Yamler:
        return Yamler.parse(
            {
                "package-ecosystem": "pip",
                "directory": "/",
                "schedule": {
                    "interval": "weekly",
                    "day": "thursday",
                },
                "groups": {
                    "python": {
                        "patterns": ["*"],
                    }
                },
            }
        )

    @staticmethod
    def _gh_actions_config() -> Yamler:
        return Yamler.parse(
            {
                "package-ecosystem": "github-actions",
                "directory": "/",
                "schedule": {
                    "interval": "weekly",
                    "day": "thursday",
                },
                "groups": {
                    "gh-actions": {
                        "patterns": ["*"],
                    }
                },
            }
        )


@dataclass(frozen=True, kw_only=True)
class CheckCodeWorkflow(YamlWorkflow):
    name: str = "CheckCode"
    path: Path = Path(".github") / "workflows" / "check_code.yml"

    @cached_property
    def steps(self) -> CiSteps:
        return CiSteps()

    @property
    def standards(self) -> Yamler:
        return (
            CiWorkflow(name="Validate Python Code")
            .with_job(
                CiJob(name="lint")
                .with_step(self.steps.checkout_code())
                .with_step(self.steps.setup_python())
                .with_step(self.steps.lint_code())
            )
            .with_job(
                CiJob(name="test-unit")
                .with_step(self.steps.checkout_code())
                .with_step(self.steps.setup_python())
                .with_step(self.steps.run_unit_tests())
            )
            .with_job(
                CiJob(name="test-integration")
                .enabled(when=Version().is_installed("pytest-docker"))
                .with_step(self.steps.checkout_code())
                .with_step(self.steps.setup_python())
                .with_step(self.steps.run_integration_tests())
            )
            .with_job(
                CiJob(name="test-behaviour")
                .enabled(when=Version().is_installed("behave"))
                .with_step(self.steps.checkout_code())
                .with_step(self.steps.setup_python())
                .with_step(self.steps.run_behaviour_tests())
            )
            .yamlify()
        )


@dataclass(frozen=True)
class CiWorkflow:
    name: str

    jobs: MutableSequence[CiJob] = field(default_factory=list)

    def with_job(self, value: CiJob) -> CiWorkflow:
        if value.is_enabled:
            self.jobs.append(value)

        return self

    def yamlify(self) -> Yamler:
        return Yamler.parse(
            {
                "name": self.name,
                "on": {"pull_request": {"branches": ["main"]}},
                "permissions": {"contents": "read"},
                "jobs": {job.name: job.yamlify() for job in self.jobs},
            }
        )


@dataclass(frozen=True)
class CiJob:
    name: str

    is_enabled: bool = True
    platform: str = "ubuntu-latest"
    steps: MutableSequence[Yamler] = field(default_factory=list)

    def with_step(self, step: Yamler) -> CiJob:
        self.steps.append(step)

        return self

    def enabled(self, when: bool) -> CiJob:
        return replace(self, is_enabled=when)

    def yamlify(self) -> Any:
        return {
            "runs-on": self.platform,
            "steps": [step.yamlify() for step in self.steps],
        }


@dataclass(frozen=True)
class CiSteps:
    cache: MutableMapping[str, Yamler] = field(default_factory=dict)

    def cached(self, **values: Yamler) -> Yamler:
        assert len(values) == 1, "cached supports one argument at a time."
        name, value = values.popitem()

        if name not in self.cache:
            self.cache[name] = value

        return self.cache[name]

    def checkout_code(self) -> Yamler:
        return self.cached(
            checkout_code=Yamler.parse(
                {
                    "name": "Checkout Code",
                    "uses": "actions/checkout@v7",
                }
            ).anchor(name="checkout")
        )

    def setup_python(self) -> Yamler:
        return self.cached(
            setup_python=Yamler.parse(
                {
                    "name": "Setup Python",
                    "uses": "actions/setup-python@v6",
                    "with": {
                        "python-version": Version.of_python(),
                        "pip-install": f"apexcodexpy=={Version()}",
                    },
                }
            ).anchor(name="setup-python")
        )

    def lint_code(self) -> Yamler:
        return Yamler.parse(
            {
                "name": "Lint Code",
                "run": "codex lint --ci",
            }
        )

    def run_unit_tests(self) -> Yamler:
        return Yamler.parse(
            {
                "name": "Run unit tests",
                "run": "codex test unit --ci",
            }
        )

    def run_integration_tests(self) -> Yamler:
        return Yamler.parse(
            {
                "name": "Run integration tests",
                "run": "codex test integration --ci",
            }
        )

    def run_behaviour_tests(self) -> Yamler:
        return Yamler.parse(
            {
                "name": "Run behaviour tests",
                "run": "codex test behaviour --ci",
            }
        )


@dataclass(frozen=True, kw_only=True)
class Yamler:
    value: Any

    def yamlify(self) -> Mapping[str, Any]:
        return dict(self.value)

    @classmethod
    def read(cls, path: Path) -> Yamler:
        return cls(value=YAML().load(path))

    @classmethod
    def parse(cls, data: Mapping[str, Any]) -> Yamler:
        serializer = YAML()
        serializer.indent(mapping=2, sequence=4, offset=2)

        stream = io.StringIO()
        serializer.dump(data, stream)

        stream.seek(0)
        loaded = serializer.load(stream)

        return cls(value=loaded)

    def anchor(self, name: str) -> Yamler:
        self.value.yaml_set_anchor(name, always_dump=True)

        return self

    def comment(self, *messages: str) -> Yamler:
        self.value.yaml_set_start_comment("\n".join(messages))

        return self

    def dump_to(self, path: Path) -> None:
        serializer = YAML()
        serializer.indent(mapping=2, sequence=4, offset=2)

        with path.open("w", newline="\n") as stream:
            serializer.dump(self.value, stream)
