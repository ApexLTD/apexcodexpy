from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import MutableMapping, MutableSequence
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from pathlib import Path

from codex.infra.program import Executable
from codex.infra.result import ProgramResult
from codex.infra.tools import Version
from codex.infra.yamler import Yamler


@dataclass(frozen=True, kw_only=True)
class YamlWorkflow(ABC):
    name: str
    path: Path

    disclaimer: bool = True

    @property
    @abstractmethod
    def standards(self) -> Yamler:
        pass

    def sync(self, target: Path, force: bool = False) -> Executable:
        path = target / self.path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch(exist_ok=True)

        standards = self.standards
        if not force and Yamler.read(path) == standards:
            return ProgramResult(name=self.name).no_changes()

        if self.disclaimer:
            standards = standards.comment(
                "Auto Generated",
                f"By: Apex Codex {Version()}",
                f"At: {self._utcnow()}",
                "Do not edit this file manually!\n\n",
            )

        standards.dump_to(path)

        return self.success()

    def _utcnow(self) -> str:
        return datetime.now(tz=UTC).replace(microsecond=0).isoformat(sep=" ")

    def success(self) -> ProgramResult:
        return ProgramResult(name=self.name).success(
            message=f"{self.name} workflow succeeded.\n"
        )


@dataclass(frozen=True, kw_only=True)
class CheckCodeWorkflow(YamlWorkflow):
    name: str = "CheckCode"
    path: Path = Path(".github") / "workflows" / "check_code.yml"

    @property
    def standards(self) -> Yamler:
        return (
            CiWorkflow(name="Validate Python Code")
            .with_job(
                CodeCheckJob(name="lint")
                .run(
                    step="Lint Code",
                    command="codex lint --ci",
                )
                .enabled(True)
            )
            .with_job(
                CodeCheckJob(name="test-unit")
                .run(
                    step="Run unit tests",
                    command="codex test unit --ci",
                )
                .enabled(True)
            )
            .with_job(
                CodeCheckJob(name="test-integration")
                .run(
                    step="Run integration tests",
                    command="codex test integration --ci",
                )
                .enabled(when=Version().is_installed("pytest-docker"))
            )
            .with_job(
                CodeCheckJob(name="test-behaviour")
                .run(
                    step="Run behaviour tests",
                    command="codex test behaviour --ci",
                )
                .enabled(when=Version().is_installed("behave"))
            )
            .yamlify()
        )


@dataclass(frozen=True)
class CiWorkflow:
    name: str

    jobs: MutableMapping[str, Yamler] = field(default_factory=dict)

    def with_job(self, value: CiJob) -> CiWorkflow:
        if value.is_enabled:
            self.jobs[value.name] = value.yamlify()

        return self

    def yamlify(self) -> Yamler:
        return Yamler.parse(
            {
                "name": self.name,
                "on": {"pull_request": {"branches": ["main"]}},
                "permissions": {"contents": "read"},
                "jobs": {name: job.as_mapping() for name, job in self.jobs.items()},
            }
        )


@dataclass(frozen=True)
class CiJob:
    name: str

    is_enabled: bool = True
    platform: str = "ubuntu-latest"
    steps: MutableSequence[Yamler] = field(default_factory=list)

    def with_step(self, step: Yamler) -> CiJob:
        self.steps.append(step)

        return self

    def run(self, step: str, command: str) -> CiJob:
        return self.with_step(Yamler.parse({"name": step, "run": command}))

    def enabled(self, when: bool) -> CiJob:
        return replace(self, is_enabled=when)

    def yamlify(self) -> Yamler:
        return Yamler.parse(
            {
                "runs-on": self.platform,
                "steps": [step.as_mapping() for step in self.steps],
            }
        )


CHECKOUT = Yamler.parse(
    {
        "name": "Checkout Code",
        "uses": "actions/checkout@v7",
    }
).anchor("checkout")

SETUP = Yamler.parse(
    {
        "name": "Setup Python",
        "uses": "actions/setup-python@v6",
        "with": {
            "python-version": Version.of_python(),
            "pip-install": f"apexcodexpy=={Version()}",
        },
    }
).anchor("setup")


@dataclass(frozen=True)
class CodeCheckJob(CiJob):
    steps: MutableSequence[Yamler] = field(default_factory=lambda: [CHECKOUT, SETUP])
